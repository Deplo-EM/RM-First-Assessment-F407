// ============================================================================
//  AngleTrack.h —— 多圈角度累计（B3 关）
//
//  【问题】GM6020 反馈的机械角度只有 0 ~ 8191（8192 个刻度 = 一圈），
//          转过一圈后会从 8191 直接跳回 0。
//          位置环要的是"连续的角度"，所以必须自己把它接起来：
//
//              读数： 8100 → 8191 → 0 → 100
//              直接用：6.21 → 6.28 → 0.00 → 0.08   ← PID 以为误差变成 −6 弧度，输出猛冲
//              接起来：6.21 → 6.28 → 6.29 → 6.36   ← 连续 ✅
//
//  【做法】最短路径累加法
//      每一帧算一个位移增量：delta = 本帧 raw − 上一帧 raw
//      如果 delta 看起来"跳得太多"（超过半圈），说明发生了跨圈，把它修正回真实的小位移：
//          delta >  +4096  →  delta -= 8192
//          delta <  -4096  →  delta += 8192
//      然后 total_ticks_ += delta，角度 = total_ticks_ × (2π / 8192)
//
//  【为什么"半圈阈值"是安全的？】
//      GM6020 最快约 320 rpm ≈ 5.3 圈/秒；1 kHz 采样下每拍只走约 44 个刻度，
//      离 4096 差得很远 —— 所以"单帧位移不会超过半圈"这个假设永远成立。
//
//  【上电第一帧要特殊处理】
//      第一帧只当作"起点"，不许产生圈数。
//      （老师的参考实现 G m6020.cpp 在这里有隐患：full_turns_ 初值 0、
//        last_raw_angle_ 初值 0，如果上电时轴不在 0 附近，第一帧就会被误判成
//        跨圈，凭空多/少一整圈。）
//
//  【坐标系约定】
//      reset() 之后的第一帧就是 0 弧度（"上电位置 = 0"）。
//      这样位置环上电时不会因为绝对角度不为 0 而猛冲。
// ============================================================================

#pragma once

#include <cstdint>

namespace rm {

class AngleTrack {
 public:
  // 清零：下一帧当作新的起点（不产生假圈数）
  void reset();

  // 每收到一帧电机反馈就调用一次（raw = 0 ~ 8191）
  void update(uint16_t raw);

  // 连续累计角度（弧度，可为负，支持多圈）
  float rad() const;

  // 连续累计圈数（带小数：转半圈 = 0.5，反转 = 负数）
  float turns() const;

  // 连续累计刻度数（整数，rad() 的"原始单位"版本，调试时最直观）
  int32_t totalTicks() const;

 private:
  bool    started_     = false;  // 是否已经收到过第一帧
  uint16_t last_raw_   = 0;      // 上一帧的原始角度
  int32_t total_ticks_ = 0;      // 连续累计的刻度数
};

}  // namespace rm
