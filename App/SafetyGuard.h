// ============================================================================
//  SafetyGuard.h —— 安全护栏（B4 关）
//
//  它是夹在 PID 和电机之间的一道"安检门"：
//
//      PID 算出电压  ──→  【SafetyGuard】  ──→  真正发给电机
//                              ↑
//                     反馈状态 / 温度 / 掉线判断
//
//  【四条规则】任何一条不通过，输出电压一律归零：
//    ① 还没收到过任何反馈 → 不许输出
//       上电瞬间最危险：PID 手里没有任何真实数据，一算就可能满电压猛冲。
//    ② 反馈超时（超过 kFeedbackTimeoutMs 没收到帧）→ 归零
//       CAN 线松了、电机掉电了、对方死了……你都必须"松脚"。
//    ③ 过温（超过 kTempLimitC）→ 归零，降到 kTempLimitC − kTempHysteresisC 以下才恢复
//    ④ 绝对电压上限 kSafeVoltageMax（双保险，跟 PID 自己的限幅是两回事）
//
//  【为什么要有"迟滞"（hysteresis）？】
//      如果恢复阈值和保护阈值一样（都在 70℃），温度在 70℃ 上下抖动时，
//      输出会疯狂地"开-关-开-关"，电机一冲一停地打嗝。
//      留 5℃ 的死区（70 触发、65 才恢复）就稳了。
//      —— 这是所有"带阈值保护"的通用技巧。
//
//  【为什么过温是"停输出"而不是"复位重启"？】
//      复位解决不了过热，只会让电机不断重启、越来越热。
//      过热需要的是"冷静下来"。
//      真正需要复位的是"程序卡死" —— 那是下一关 B5 看门狗的工作。
//
//  【调用时机】（和真实中断对应）
//      onFeedback()：CAN 接收中断里（每收到一帧调用一次）
//      tick()      ：1 ms 控制中断里（每个控制拍调用一次）
// ============================================================================

#pragma once

#include <cstdint>

namespace rm {

class SafetyGuard {
 public:
  // 上电/重新开始：回到"还没收到反馈"的状态
  void reset();

  // 收到一帧电机反馈时调用（CAN 接收中断里）
  void onFeedback();

  // 每个控制拍（1 ms）调用一次，传入当前温度
  void tick(float temp_c);

  // 现在允许输出吗？（反馈健康 且 温度正常）
  bool allowed() const;

  // 把电压指令夹进安全范围；不允许输出时返回 0
  float limit(float u) const;

  // 反馈是否健康（B5 看门狗判断"要不要喂狗"时也要用）
  bool feedbackOk() const;

  // 温度是否正常
  bool tempOk() const;

 private:
  uint32_t ticks_since_feedback_ = 0;  // 距上次收到反馈过了几个控制拍
  bool     started_              = false;  // 是否已经收到过第一帧反馈
  float    temp_c_               = 0.0f;   // 最近一次温度
  bool     over_temp_            = false;  // 是否处于过温保护状态（迟滞用）
};

}  // namespace rm
